#!/usr/bin/env node
// make-icons: draws the app icon (two overlapping play triangles, one per viewer, on a rounded square in the theme's
// accent colours) and renders every format electron-builder needs into build/ (its buildResources directory):
//   build/icon.svg            the drawing: full-bleed tile, used for Windows and Linux
//   build/icon-macos.svg      the same on Apple's 824-of-1024 grid with a drop shadow, used for macOS
//   build/icon.png            icon.svg at 1024 px
//   build/icons/<n>x<n>.png   Linux hicolor sizes 16-512; deb/rpm/pacman/AppImage install these
//   build/icon.ico            Windows: 16-256 px, 32-bit BMP entries (ImageMagick), which every tool accepts
//   build/icon.icns           macOS: PNG entries 16-1024 px, assembled here, so iconutil is not needed
// electron-builder picks icon.icns (mac), icon.ico (win) and icons/ (linux) from build/ by name, so it never has to
// convert anything. Colours come from src/shared/theme-tokens.ts (imported with Node's TypeScript type stripping).
// Requires Node >= 24, rsvg-convert (librsvg) and ImageMagick 7 (`magick`).
// Usage: node scripts/make-icons.mjs
import { Buffer } from 'node:buffer'
import { execFileSync } from 'node:child_process'
import console from 'node:console'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, relative, resolve } from 'node:path'
import { URL } from 'node:url'

const ROOT = resolve(import.meta.dirname, '..')
const BUILD = join(ROOT, 'build')
const { THEME_TOKENS } = await import(new URL('../src/shared/theme-tokens.ts', import.meta.url).href)

const LINUX_SIZES = [16, 22, 24, 32, 48, 64, 128, 256, 512]
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
// ICNS element types that hold PNG data, with the pixel size each expects (ic11-ic14 are the @2x variants).
const ICNS_TYPES = [
  ['icp4', 16],
  ['icp5', 32],
  ['icp6', 64],
  ['ic07', 128],
  ['ic08', 256],
  ['ic09', 512],
  ['ic10', 1024],
  ['ic11', 32],
  ['ic12', 64],
  ['ic13', 256],
  ['ic14', 512],
]

const COLORS = {
  from: THEME_TOKENS.dark.accent, // top-left of the tile
  to: THEME_TOKENS.light.accent, // bottom-right
  back: THEME_TOKENS.light['tl-downloading'],
  front: '#ffffff',
}

/**
 * The icon on a 1024 canvas. The glyph is laid out in tile units (0-1000) and mapped to canvas pixels, so the
 * background gradient, which the halo reuses, stays in one coordinate system.
 */
function drawIcon({ inset, radius, shadow }) {
  const size = 1024 - 2 * inset
  const k = size / 1000
  const h = 400 // triangle height in tile units
  const w = (h * Math.sqrt(3)) / 2
  const stroke = 70 // same-colour stroke with round joins: soft corners
  const gap = 30 // background-coloured halo between the two triangles
  const tri = (cx, cy) => [
    [cx - w / 3, cy - h / 2],
    [cx - w / 3, cy + h / 2],
    [cx + (2 * w) / 3, cy],
  ]
  // The back triangle sits up and to the left by (ox, oy) with oy = ox * sqrt(3): it then shows the same width past
  // the front one's left edge as past its top edge, and hides completely behind its bottom edge.
  const ox = 110
  let back = tri(500 - ox, 500 - ox * Math.sqrt(3))
  let front = tri(500, 500)
  // Centre the pair (with its stroke) in the tile, nudged right a little: a play glyph looks left-heavy otherwise.
  const pts = [...back, ...front]
  const [minX, maxX] = [Math.min(...pts.map((p) => p[0])), Math.max(...pts.map((p) => p[0]))]
  const [minY, maxY] = [Math.min(...pts.map((p) => p[1])), Math.max(...pts.map((p) => p[1]))]
  const dx = 500 - (minX + maxX) / 2 + 14
  const dy = 500 - (minY + maxY) / 2
  const place = (t) => t.map(([x, y]) => [inset + (x + dx) * k, inset + (y + dy) * k])
  back = place(back)
  front = place(front)
  const d = (t) => `M${t.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join(' L')} Z`
  const px = (n) => (n * k).toFixed(1)
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/make-icons.mjs; edit that script, not this file. -->
  <defs>
    <linearGradient id="bg" gradientUnits="userSpaceOnUse" x1="${inset}" y1="${inset}" x2="${1024 - inset}" y2="${1024 - inset}">
      <stop offset="0" stop-color="${COLORS.from}"/>
      <stop offset="1" stop-color="${COLORS.to}"/>
    </linearGradient>${
      shadow
        ? `
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%" color-interpolation-filters="sRGB">
      <feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="#000000" flood-opacity="0.3"/>
    </filter>`
        : ''
    }
  </defs>
  <rect x="${inset}" y="${inset}" width="${size}" height="${size}" rx="${radius}" fill="url(#bg)"${shadow ? ' filter="url(#shadow)"' : ''}/>
  <g stroke-linejoin="round">
    <path d="${d(back)}" fill="${COLORS.back}" stroke="${COLORS.back}" stroke-width="${px(stroke)}"/>
    <path d="${d(front)}" fill="url(#bg)" stroke="url(#bg)" stroke-width="${px(stroke + 2 * gap)}"/>
    <path d="${d(front)}" fill="${COLORS.front}" stroke="${COLORS.front}" stroke-width="${px(stroke)}"/>
  </g>
</svg>
`
}

function render(svgFile, px, outFile) {
  execFileSync('rsvg-convert', [
    '--width',
    String(px),
    '--height',
    String(px),
    '--format',
    'png',
    '--output',
    outFile,
    svgFile,
  ])
}

function icns(entries) {
  const chunk = (type, data) => {
    const head = Buffer.alloc(8)
    head.write(type, 0, 'latin1')
    head.writeUInt32BE(data.length + 8, 4)
    return Buffer.concat([head, data])
  }
  return chunk('icns', Buffer.concat(entries.map(([type, png]) => chunk(type, png))))
}

/** [width, height] of each image in an .ico, read from its directory. */
function icoSizes(buf) {
  if (buf.readUInt16LE(0) !== 0 || buf.readUInt16LE(2) !== 1) throw new Error('not an ICO file')
  return Array.from({ length: buf.readUInt16LE(4) }, (_, i) => [buf[6 + i * 16] || 256, buf[7 + i * 16] || 256])
}

const pngSize = (buf) => [buf.readUInt32BE(16), buf.readUInt32BE(20)]

async function main() {
  const tmp = await mkdtemp(join(tmpdir(), 'wt-icons-'))
  try {
    await mkdir(join(BUILD, 'icons'), { recursive: true })
    const fullSvg = join(BUILD, 'icon.svg')
    const macSvg = join(BUILD, 'icon-macos.svg')
    // Full bleed with a small margin (Windows, Linux); Apple's template: 824 px tile, 185 px corners, a shadow.
    await writeFile(fullSvg, drawIcon({ inset: 32, radius: 216, shadow: false }))
    await writeFile(macSvg, drawIcon({ inset: 100, radius: 185, shadow: true }))

    render(fullSvg, 1024, join(BUILD, 'icon.png'))
    for (const n of LINUX_SIZES) render(fullSvg, n, join(BUILD, 'icons', `${String(n)}x${String(n)}.png`))

    const icoInputs = ICO_SIZES.map((n) => {
      const file = join(tmp, `ico-${String(n)}.png`)
      render(fullSvg, n, file)
      return file
    })
    execFileSync('magick', [...icoInputs, join(BUILD, 'icon.ico')])

    const macPngs = new Map()
    for (const n of new Set(ICNS_TYPES.map(([, n]) => n))) {
      const file = join(tmp, `mac-${String(n)}.png`)
      render(macSvg, n, file)
      macPngs.set(n, await readFile(file))
    }
    await writeFile(join(BUILD, 'icon.icns'), icns(ICNS_TYPES.map(([type, n]) => [type, macPngs.get(n)])))

    // Read everything back, so a broken tool fails here rather than inside electron-builder.
    const report = []
    for (const f of ['icon.png', ...LINUX_SIZES.map((n) => `icons/${String(n)}x${String(n)}.png`)]) {
      report.push(`${f} ${pngSize(await readFile(join(BUILD, f))).join('x')}`)
    }
    const ico = icoSizes(await readFile(join(BUILD, 'icon.ico')))
    if (Math.max(...ico.map(([w]) => w)) < 256) throw new Error('icon.ico has no 256 px image')
    report.push(`icon.ico ${ico.map(([w, h]) => `${String(w)}x${String(h)}`).join(' ')}`)
    const icnsBuf = await readFile(join(BUILD, 'icon.icns'))
    if (icnsBuf.toString('latin1', 0, 4) !== 'icns' || icnsBuf.readUInt32BE(4) !== icnsBuf.length) {
      throw new Error('icon.icns is malformed')
    }
    report.push(`icon.icns ${ICNS_TYPES.map(([t, n]) => `${t}:${String(n)}`).join(' ')}`)
    for (const line of report) console.log(`[make-icons] build/${line}`)
    console.log(`[make-icons] wrote ${relative(ROOT, fullSvg)} and ${relative(ROOT, macSvg)}`)
  } finally {
    await rm(tmp, { recursive: true, force: true })
  }
}

await main()
